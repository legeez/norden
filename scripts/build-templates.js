// Runs at BUILD time (not on Cloudflare) — walks views/, reads every .ejs file,
// and writes a single JS module exporting { "index": "<source>", "admin/login": "<source>", ... }.
//
// Why: Cloudflare Workers has no real filesystem to read template files from at
// request time, so instead of EJS reading files off disk (what it does by
// default in plain Node), we bundle every template's source text directly into
// the deployed code. lib/render.js then compiles them all once at startup.
//
// Run with: npm run build:templates
const fs = require('fs');
const path = require('path');

const VIEWS_DIR = path.join(__dirname, '..', 'views');
const OUT_FILE = path.join(__dirname, '..', 'worker', 'templates.generated.js');

function walk(dir, base = '') {
  const entries = fs.readdirSync(dir, { withFileTypes: true });
  let files = [];
  for (const entry of entries) {
    const full = path.join(dir, entry.name);
    const rel = base ? `${base}/${entry.name}` : entry.name;
    if (entry.isDirectory()) {
      files = files.concat(walk(full, rel));
    } else if (entry.name.endsWith('.ejs')) {
      files.push(rel.replace(/\.ejs$/, ''));
    }
  }
  return files;
}

function build() {
  const names = walk(VIEWS_DIR);
  const templates = {};
  names.forEach(name => {
    const filePath = path.join(VIEWS_DIR, `${name}.ejs`);
    templates[name] = fs.readFileSync(filePath, 'utf-8');
  });

  const banner = '// AUTO-GENERATED by scripts/build-templates.js — do not edit by hand.\n// Regenerate with: npm run build:templates\n';
  const body = `module.exports = ${JSON.stringify(templates, null, 2)};\n`;

  fs.mkdirSync(path.dirname(OUT_FILE), { recursive: true });
  fs.writeFileSync(OUT_FILE, banner + body);
  console.log(`Bundled ${names.length} templates -> ${path.relative(process.cwd(), OUT_FILE)}`);
}

build();
